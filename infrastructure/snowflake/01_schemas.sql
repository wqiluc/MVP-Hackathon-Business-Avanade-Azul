CREATE SCHEMA IF NOT EXISTS BRONZE;
CREATE SCHEMA IF NOT EXISTS SILVER;
CREATE SCHEMA IF NOT EXISTS GOLD;

CREATE TABLE IF NOT EXISTS BRONZE.BRONZE_CLIENTS (
    ID_CLIENTE VARCHAR,
    TIER VARCHAR,
    FREQUENCIA NUMBER(38, 0),
    RECENCIA_DIAS NUMBER(38, 0),
    GASTO_TOTAL FLOAT,
    INCIDENTES NUMBER(38, 0)
);

CREATE TABLE IF NOT EXISTS SILVER.CLEANED_CLIENTS (
    CLIENT_IDENTIFIER VARCHAR,
    TIER VARCHAR,
    FREQUENCY NUMBER(38, 0),
    RECENCY_DAYS NUMBER(38, 0),
    TOTAL_SPEND FLOAT,
    FLIGHT_INCIDENTS NUMBER(38, 0),
    INGESTED_AT TIMESTAMP_TZ
);

CREATE TABLE IF NOT EXISTS GOLD.CLIENT_FEATURES (
    CLIENT_IDENTIFIER VARCHAR,
    TIER VARCHAR,
    FREQUENCY NUMBER(38, 0),
    RECENCY_DAYS NUMBER(38, 0),
    TOTAL_SPEND FLOAT,
    FLIGHT_INCIDENTS NUMBER(38, 0),
    AVG_TICKET FLOAT,
    HIGH_RISK_FLAG NUMBER(1, 0),
    CHURN_SCORE FLOAT
);
