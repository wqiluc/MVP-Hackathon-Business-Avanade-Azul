CREATE OR REPLACE TABLE GOLD.CLIENT_FEATURES AS
SELECT
    CLIENT_IDENTIFIER,
    TIER,
    FREQUENCY,
    RECENCY_DAYS,
    TOTAL_SPEND,
    FLIGHT_INCIDENTS,
    ROUND(TOTAL_SPEND / NULLIF(FREQUENCY, 0), 2) AS AVG_TICKET,
    CASE
        WHEN FLIGHT_INCIDENTS >= 2 OR RECENCY_DAYS > 60 THEN 1
        ELSE 0
    END AS HIGH_RISK_FLAG,
    CAST(NULL AS FLOAT) AS CHURN_SCORE
FROM SILVER.CLEANED_CLIENTS;
