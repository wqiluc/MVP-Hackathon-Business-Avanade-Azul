-- DDL Arquitetura Medalhão Snowflake - Projeto AeroShield / Azul
CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH WITH WAREHOUSE_SIZE = 'X-SMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;
CREATE DATABASE IF NOT EXISTS AZUL_DATA_LAKE;

CREATE SCHEMA IF NOT EXISTS AZUL_DATA_LAKE.BRONZE;
CREATE SCHEMA IF NOT EXISTS AZUL_DATA_LAKE.SILVER;
CREATE SCHEMA IF NOT EXISTS AZUL_DATA_LAKE.GOLD;

-- Tabela Bronze
CREATE TABLE IF NOT EXISTS AZUL_DATA_LAKE.BRONZE.INGESTAO_RAW (
    id VARCHAR(36) DEFAULT UUID_STRING() PRIMARY KEY,
    origem_arquivo VARCHAR(255) NOT NULL,
    formato_original VARCHAR(50) NOT NULL,
    payload_bruto VARIANT NOT NULL,
    recebido_em TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Tabela Silver
CREATE TABLE IF NOT EXISTS AZUL_DATA_LAKE.SILVER.CLIENTES (
    cpf VARCHAR(11) PRIMARY KEY,
    nome VARCHAR(150),
    email VARCHAR(150),
    uf VARCHAR(2),
    nivel_fidelidade VARCHAR(30),
    saldo_pontos NUMBER(10, 0) DEFAULT 0,
    pontos_a_expirar NUMBER(10, 0) DEFAULT 0,
    canal_aquisicao VARCHAR(100),
    atualizado_em TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Tabela Gold
CREATE TABLE IF NOT EXISTS AZUL_DATA_LAKE.GOLD.ANALISE_RETENCAO (
    cpf VARCHAR(11) PRIMARY KEY,
    status_retencao VARCHAR(30),
    risco_churn_score NUMBER(3, 2),
    ltv_total_gasto NUMBER(12, 2),
    divisao_principal VARCHAR(50),
    divisao_cross_sell VARCHAR(50),
    acao_recomendada VARCHAR(255),
    calculado_em TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);