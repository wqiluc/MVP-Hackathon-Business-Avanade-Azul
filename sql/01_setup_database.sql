-- 1. Poder de processamento
CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH
  WITH WAREHOUSE_SIZE = 'X-SMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE;

-- 2. Banco e Schemas Medalhão
CREATE DATABASE IF NOT EXISTS AZUL_DATA_LAKE;
CREATE SCHEMA IF NOT EXISTS AZUL_DATA_LAKE.BRONZE;
CREATE SCHEMA IF NOT EXISTS AZUL_DATA_LAKE.SILVER;
CREATE SCHEMA IF NOT EXISTS AZUL_DATA_LAKE.GOLD;

-- 3. Papel de segurança com permissões mínimas
CREATE ROLE IF NOT EXISTS APP_ROLE;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE APP_ROLE;
GRANT ALL ON DATABASE AZUL_DATA_LAKE TO ROLE APP_ROLE;
GRANT ALL ON ALL SCHEMAS IN DATABASE AZUL_DATA_LAKE TO ROLE APP_ROLE;